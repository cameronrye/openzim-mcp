# 5. Documentation that would mislead a reader on a DEFAULT install.
# --------------------------------------------------------------------------

_DOC_PAGES = sorted((REPO / "website" / "src" / "content" / "docs").glob("*.mdx"))

# The body of a fenced block, with its info string. Only fenced blocks are
# scanned: prose *about* a bad phrasing (troubleshooting says "do not ask
# ...") must stay legal, while the same words offered as something to run
# must not.
_FENCE_RE = re.compile(r"^```([a-z]*)\n(.*?)^```", re.MULTILINE | re.DOTALL)
_HEALTH_ASK_RE = re.compile(r"server (?:health|configuration)", re.IGNORECASE)


def test_no_page_offers_a_natural_language_server_health_ask() -> None:
    """Simple mode is the default and has no health intent.

    ``zim_health`` is registered in advanced mode only, and the intent parser
    has nothing that routes a health or configuration request — so a phrase
    like "check the server health and configuration", offered in a fenced
    block as something to ask, is parsed as a *topic* and searched inside the
    archive. The reader gets ``No search results found`` and reads it as a
    broken server. Both the troubleshooting page's first diagnostic and the
    configuration page's validation step shipped exactly that.

    The premise is asserted first, so this test fails loudly rather than
    silently going vacuous if a health intent is ever added.
    """
    from openzim_mcp.intent_parser import IntentParser

    parser = IntentParser()
    probe = "check the server health and configuration"
    intent, _params, _confidence = parser.parse_intent(probe)
    assert intent not in {"health", "server_health", "configuration", "config"}, (
        f"the intent parser now routes {probe!r} to {intent!r}. Simple mode can "
        "answer a health ask after all — delete this test and restore the "
        "natural-language examples it forbids."
    )

    offenders: list[str] = []
    for path in _DOC_PAGES:
        text = path.read_text(encoding="utf-8")
        for match in _FENCE_RE.finditer(text):
            body = match.group(2)
            if not _HEALTH_ASK_RE.search(body):
                continue
            # `zim_health()` and the HTTP probes are the correct advanced-mode
            # and transport-level answers; only a quoted natural-language ask
            # is the defect.
            for line in body.splitlines():
                stripped = line.strip()
                if not _HEALTH_ASK_RE.search(stripped):
                    continue
                if stripped.startswith('"') or stripped.startswith("'"):
                    lineno = text[: match.start()].count("\n") + 1
                    rel = path.relative_to(REPO)
                    offenders.append(f"{rel}:~{lineno}: {stripped}")

    assert not offenders, (
        "a fenced block offers a natural-language server-health ask, which "
        "reaches nothing on a default (simple-mode) install and searches the "
        "archive for those words instead. Use `zim_health()` and say it needs "
        "advanced mode, or use the `/healthz` and `/readyz` probes:\n  "
        + "\n  ".join(offenders)
    )


