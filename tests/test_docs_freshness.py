_LAYOUTS = sorted((REPO / "website" / "src" / "layouts").glob("*.astro"))

_CSS_COMMENT_RE = re.compile(r"/\*.*?\*/", re.DOTALL)
_CSS_RULE_RE = re.compile(r"([^{}]*)\{([^{}]*)\}")
_OPACITY_ZERO_RE = re.compile(r"opacity:\s*0\s*[;}]")


def test_reveal_animation_does_not_hide_content_without_js() -> None:
    """`[data-reveal] { opacity: 0 }` unscoped is a blank page with JS off.

    Four of the landing page's five sections were invisible to anyone without
    scripting, and invisible again any time the deferred bundle failed to
    load: the CSS hid them unconditionally and only `script.js` ever added the
    `.revealed` class that brought them back. The hiding half is now scoped to
    `.js`, which a head script adds and — crucially — removes again on `load`
    if `script.js` never announced itself.

    Comments are stripped before matching, or a comment mentioning `.js` next
    to the rule would satisfy this test without the rule being scoped at all.
    """
    css = _CSS_COMMENT_RE.sub("", _STYLES_CSS.read_text(encoding="utf-8"))

    checked = 0
    unscoped: list[str] = []
    for selector, body in _CSS_RULE_RE.findall(css):
        if "[data-reveal]" not in selector or not _OPACITY_ZERO_RE.search(body):
            continue
        checked += 1
        if ".js" not in selector:
            unscoped.append(" ".join(selector.split()))
    assert checked, (
        "no `[data-reveal]` rule setting `opacity: 0` was found in styles.css — "
        "this test has gone vacuous; the reveal mechanism was renamed or removed"
    )
    assert not unscoped, (
        "these rules hide `[data-reveal]` content for every visitor, including "
        f"those `script.js` never reaches: {unscoped}. Scope them under `.js`."
    )

    script = _SCRIPT_JS.read_text(encoding="utf-8")
    assert "classList.add('js-ready')" in script, (
        "script.js must announce itself with `js-ready`; the layouts' head "
        "script strips `.js` on `load` without it, so the reveal would never "
        "arm and the animation would be dead"
    )

    # Every layout, unconditionally. styles.css is a single site-wide sheet,
    # so the `.js` contract is site-wide too: a layout without the flag renders
    # any `[data-reveal]` markup beneath it permanently hidden. Scoping this
    # check to layouts that mention script.js let a mutation through — neither
    # layout links the bundle directly (index.astro and DocsLayout's body do),
    # so the check covered nothing that mattered.
    assert _LAYOUTS, "no layouts found — this test has gone vacuous"
    missing_flag = [
        str(path.relative_to(REPO))
        for path in _LAYOUTS
        if "classList.add('js')" not in path.read_text(encoding="utf-8")
    ]
    assert not missing_flag, (
        f"these layouts never set the `.js` flag: {missing_flag}. Any "
        "`[data-reveal]` section rendered beneath one stays at `opacity: 0` "
        "forever, because only `.js [data-reveal].revealed` brings it back."
    )
    missing_fallback = [
        str(path.relative_to(REPO))
        for path in _LAYOUTS
        if "classList.remove('js')" not in path.read_text(encoding="utf-8")
    ]
    assert not missing_fallback, (
        f"these layouts add `.js` but never remove it: {missing_fallback}. The "
        "`load` fallback is what keeps a failed script.js from leaving the page "
        "permanently at `opacity: 0`."
    )


